import { ReviewStore } from "./review-store.mjs";
import { PILOT_FILES } from "./review-fixture.mjs";

export const REVIEW_TOOLS = Object.freeze([
  {
    type: "function", function: {
      name: "inspect_project", description: "List and read the two editable files: index.html and styles.css.",
      parameters: { type: "object", properties: {}, required: [] }
    }
  },
  {
    type: "function", function: {
      name: "write_file", description: "Replace exactly one allowed file with complete contents. You must update both files.",
      parameters: { type: "object", properties: {
        path: { type: "string", enum: [...PILOT_FILES] }, content: { type: "string" }
      }, required: ["path", "content"] }
    }
  },
  {
    type: "function", function: {
      name: "run_checks", description: "Run trusted static checks without executing code generated by the model.",
      parameters: { type: "object", properties: {}, required: [] }
    }
  },
  {
    type: "function", function: {
      name: "finish", description: "Finish only after both files changed and every check passed.",
      parameters: { type: "object", properties: { summary: { type: "string" } }, required: ["summary"] }
    }
  }
]);

const PROMPT = [
  "You are a tool-using coding agent operating on an isolated two-file sample web app.",
  "Modify index.html and styles.css to add a visually styled, keyboard-accessible Start demo button.",
  "Use ONLY provided function tools. Do not emit code outside of tools.",
  "Plan:",
  "1. Call inspect_project to read BOTH files.",
  "2. Write index.html. Preserve the exact h1 text 'Local AI Studio', the local styles.css link and the existing description.",
  "   Add <button id=\"start-demo\" aria-label=\"Start demo\">Start demo</button> inside main.",
  "3. Write styles.css. Add a #start-demo { background: ...; } rule, and",
  "   a #start-demo:focus-visible { outline: ...; } rule.",
  "4. Call run_checks. Fix failures using write_file and run_checks again.",
  "5. Call finish only after the checks pass and both files were written.",
  "No JS, URLs, CSS imports, shell commands, extra files, library installs, or external providers.",
  "All generated code is treated as untrusted input by the tools."
].join("\n");

function requireLocalBase(baseUrl) {
  const url = new URL(baseUrl);
  if (url.protocol !== "http:" || !["localhost", "127.0.0.1"].includes(url.hostname) ||
    url.pathname !== "/" || url.search || url.hash || url.username || url.password ||
    !url.port) throw Error("local-inference-only");
  return url.origin;
}

export async function runReviewAgent({
  store, model = "qwen3.5:9b", baseUrl = "http://127.0.0.1:11555",
  fetchImpl = fetch, maxSteps = 10, onEvent = () => {}, signal
}) {
  if (!(store instanceof ReviewStore)) throw Error("trusted-store-required");
  const origin = requireLocalBase(baseUrl);
  if (!/^[\w.:/-]{3,120}$/.test(model)) throw Error("invalid-model");
  if (!Number.isInteger(maxSteps) || maxSteps < 1 || maxSteps > 16) throw Error("invalid-step-limit");
  const session = await store.create();
  const events = [];
  const modified = new Set();
  let inspected = false;
  let checksPassed = false;
  let summary = null;
  const messages = [
    { role: "system", content: PROMPT },
    { role: "user", content: "Make the requested changes using the tools and verify." }
  ];
  const emit = data => {
    const event = { timestamp: new Date().toISOString(), ...data };
    events.push(event);
    onEvent(event);
  };
  emit({ kind: "review-created", id: session.id, branch: session.branch });

  try {
    for (let step = 1; step <= maxSteps && summary === null; step++) {
      signal?.throwIfAborted();
      const response = await fetchImpl(origin + "/api/chat", {
        method: "POST", headers: { "Content-Type": "application/json" },
        signal: signal ? AbortSignal.any([signal, AbortSignal.timeout(115000)]) : AbortSignal.timeout(115000),
        body: JSON.stringify({
          model, stream: false, think: false,
          messages, tools: REVIEW_TOOLS,
          options: { num_ctx: 16384, num_predict: 2500, temperature: 0.1 }
        })
      });
      if (!response.ok) throw Error("model-http-" + response.status);
      const result = await response.json();
      const assistant = result.message ?? {};
      const calls = Array.isArray(assistant.tool_calls) ? assistant.tool_calls : [];
      emit({ kind: "inference", step, toolCount: calls.length });
      if (!calls.length) {
        messages.push({ role: "assistant", content: String(assistant.content ?? "").slice(0, 6000) });
        messages.push({ role: "user", content: "Continue by calling the appropriate function tools. Do not stop before tests pass." });
        continue;
      }
      messages.push({ role: "assistant", content: String(assistant.content ?? ""), tool_calls: calls });
      for (const call of calls) {
        const name = call?.function?.name;
        let feedback;
        let success = false;
        try {
          let args = call?.function?.arguments || {};
          if (typeof args === "string") args = JSON.parse(args);
          if (!args || typeof args !== "object" || Array.isArray(args)) throw Error("invalid-tool-arguments");
          switch (name) {
            case "inspect_project":
              feedback = { files: await store.inspect(session.id), editable: [...PILOT_FILES] };
              inspected = true;
              break;
            case "write_file":
              if (!inspected) throw Error("inspect-first");
              feedback = await store.write(session.id, args.path, args.content);
              modified.add(args.path);
              checksPassed = false;
              break;
            case "run_checks":
              if (!PILOT_FILES.every(f => modified.has(f))) throw Error("both-files-must-be-edited");
              feedback = await store.checks(session.id);
              checksPassed = feedback.passed;
              break;
            case "finish":
              if (!checksPassed || !PILOT_FILES.every(f => modified.has(f))) throw Error("checks-not-passed");
              summary = String(args.summary ?? "").trim().slice(0, 280) || "Two-file demo completed.";
              feedback = { finished: true, summary };
              break;
            default:
              throw Error("tool-not-allowlisted");
          }
          success = true;
        } catch (error) {
          feedback = { error: String(error?.message ?? error).slice(0, 180) };
        }
        emit({ kind: "tool", step, tool: String(name ?? "unknown"), ok: success,
          passed: name === "run_checks" ? checksPassed : undefined,
          error: success ? undefined : feedback.error });
        messages.push({ role: "tool", tool_name: String(name ?? "unknown"),
          content: JSON.stringify(feedback) });
        if (summary !== null) break;
      }
    }

    const prepared = await store.prepare(session.id);
    const ok = prepared.status === "pending" && summary !== null;
    if (!ok && prepared.status === "pending") await store.fail(session.id, "agent-incomplete");
    const review = ok ? prepared : await store.get(session.id);
    emit({ kind: "result", id: session.id, ok, status: review.status });
    return {
      ok, id: session.id,
      review: store.publicReview(review), summary: summary ?? "Agent did not complete a valid review.",
      checks: prepared.checks, diff: await store.diff(session.id), events
    };
  } catch (error) {
    await store.fail(session.id, "agent-error: " + String(error?.message ?? error));
    emit({ kind: "error", id: session.id, error: String(error?.message ?? error).slice(0, 180) });
    throw error;
  }
}
